const generatedHeader = "// Code generated by internal/cmd/generate from openapi/openapi.json. DO NOT EDIT.\n\n"

// comment writes text as a Go comment, wrapped at about 100 columns, each paragraph kept.
func comment(b *strings.Builder, indent, text string) {
	for i, para := range strings.Split(strings.TrimSpace(text), "\n\n") {
		if i > 0 {
			fmt.Fprintf(b, "%s//\n", indent)
		}
		line := ""
		for _, word := range strings.Fields(para) {
			if line != "" && len(indent)+3+len(line)+1+len(word) > 100 {
				fmt.Fprintf(b, "%s// %s\n", indent, line)
				line = ""
			}
			if line != "" {
				line += " "
			}
			line += word
		}
		if line != "" {
			fmt.Fprintf(b, "%s// %s\n", indent, line)
		}
	}
}

func fieldType(kind string, required bool) string {
	switch kind {
	case "strings":
		return "[]string"
	case "string", "int", "bool":
		if required {
			return kind
		}
		return "*" + kind
	case "time":
		if required {
			return "time.Time"
		}
		return "*time.Time"
	}
	panic("a query kind with no Go type: " + kind)
}

// methodArgs is a method's arguments after ctx, as declared and as passed on.
func (o operation) methodArgs() (declared []string, names []string) {
	for _, p := range o.PathParams {
		name := localName(p)
		declared = append(declared, name+" string")
		names = append(names, name)
	}
	if o.Body != "" {
		declared = append(declared, "body "+o.Body)
		names = append(names, "body")
	}
	if len(o.Query) > 0 {
		declared = append(declared, "params "+o.ParamsType())
		names = append(names, "params")
	}
	return declared, names
}

func (o operation) decoder() string {
	if o.Answer == "fhir.Resource" {
		return "fhir.DecodeResource"
	}
	return "decodeAs[" + strings.TrimPrefix(o.Answer, "*") + "]"
}

// sendArgs is what a method or a batch entry hands to the shared code: the path values, the
// query and its error, and the body.
func (o operation) sendArgs() (pathValues, prelude, query, body string) {
	pathValues = "nil"
	_, names := o.methodArgs()
	var values []string
	for _, n := range names {
		if n != "body" && n != "params" {
			values = append(values, n)
		}
	}
	if len(values) > 0 {
		pathValues = "[]string{" + strings.Join(values, ", ") + "}"
	}
	query = "nil, nil"
	if len(o.Query) > 0 {
		prelude = "\tquery, err := params.query()\n"
		query = "query, err"
	}
	body = "nil"
	switch {
	case o.Body == "fhir.Resource":
		body = "resourceBody(body)"
	case o.Body != "":
		body = "bodyOf(body)"
	}
	return
}

// usesTime reports whether any operation takes a time.Time.
func (s *spec) usesTime() bool {
	for _, o := range s.Operations {
		for _, p := range o.Query {
			if p.Kind == "time" {
				return true
			}
		}
	}
	return false
}

func emitOperations(s *spec) string {
	var b strings.Builder
	timeImport := ""
	if s.usesTime() {
		timeImport = "\t\"time\"\n"
	}
	b.WriteString(generatedHeader + "package haau3\n\nimport (\n\t\"context\"\n" + timeImport + "\n\t\"github.com/haau3/haau3-go/fhir\"\n)\n\n")
	fmt.Fprintf(&b, "// SpecVersion is the version of the API's spec this release was generated from.\nconst SpecVersion = %q\n\n", s.Version)

	b.WriteString("// Each operation of the spec: its method, its path and what its answer may be.\nvar (\n")
	for _, o := range s.Operations {
		fmt.Fprintf(&b, "\top%s = operation{id: %q, method: %q, path: %q", o.Name, o.ID, o.Method, o.Path)
		if len(o.Expects) > 0 {
			fmt.Fprintf(&b, ", expects: %#v", o.Expects)
		}
		if o.Body != "" {
			fmt.Fprintf(&b, ", bodyTypes: %#v", o.BodyTypes)
		}
		b.WriteString("}\n")
	}
	b.WriteString(")\n\n")

	for _, o := range s.Operations {
		if len(o.Query) == 0 {
			continue
		}
		fmt.Fprintf(&b, "// %s holds %s's query parameters. A nil field is not sent.\ntype %s struct {\n", o.ParamsType(), o.Name, o.ParamsType())
		for i, p := range o.Query {
			if i > 0 {
				b.WriteString("\n")
			}
			doc := fmt.Sprintf("%s is `%s`", p.Name, p.Wire)
			if p.Required {
				doc += ", required"
			}
			doc += "."
			if p.Description != "" {
				doc += " " + p.Description
			}
			if len(p.Enum) > 0 {
				doc += " One of: " + strings.Join(p.Enum, ", ") + "."
			}
			comment(&b, "\t", doc)
			fmt.Fprintf(&b, "\t%s %s\n", p.Name, fieldType(p.Kind, p.Required))
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "func (p %s) query() (query, error) {\n\tvar q query\n", o.ParamsType())
		for _, p := range o.Query {
			switch {
			case p.Required && p.Kind == "strings":
				fmt.Fprintf(&b, "\tif err := q.requiredStrings(%q, p.%s); err != nil {\n\t\treturn nil, err\n\t}\n", p.Wire, p.Name)
			case p.Required && p.Kind == "string":
				fmt.Fprintf(&b, "\tif err := q.requiredString(%q, p.%s); err != nil {\n\t\treturn nil, err\n\t}\n", p.Wire, p.Name)
			case p.Required:
				panic("a required " + p.Kind + " query parameter, which the generator does not write: " + p.Wire)
			default:
				fmt.Fprintf(&b, "\tq.%s(%q, p.%s)\n", p.Kind, p.Wire, p.Name)
			}
		}
		b.WriteString("\treturn q, nil\n}\n\n")
	}

	for _, o := range s.Operations {
		declared, _ := o.methodArgs()
		pathValues, prelude, query, body := o.sendArgs()
		doc := fmt.Sprintf("%s: %s.", o.Name, strings.TrimSuffix(o.Summary, "."))
		if o.Description != "" {
			doc += "\n\n" + o.Description
		}
		doc += fmt.Sprintf("\n\n%s (%s): %s", o.Label(), o.ID, o.Docs)
		comment(&b, "", doc)
		args := strings.Join(append([]string{"ctx context.Context"}, append(declared, "opts ...Option")...), ", ")
		fmt.Fprintf(&b, "func (c *Client) %s(%s) (%s, error) {\n", o.Name, args, o.Answer)
		if prelude == "" {
			fmt.Fprintf(&b, "\treturn call(ctx, c, &op%s, %s, %s, %s, %s, opts)\n}\n\n", o.Name, pathValues, query, body, o.decoder())
		} else {
			fmt.Fprintf(&b, "%s\treturn call(ctx, c, &op%s, %s, %s, %s, %s, opts)\n}\n\n", prelude, o.Name, pathValues, query, body, o.decoder())
		}
	}

	for _, o := range s.Operations {
		if !o.Batchable {
			continue
		}
		declared, _ := o.methodArgs()
		pathValues, prelude, query, body := o.sendArgs()
		comment(&b, "", fmt.Sprintf("%s is Client.%s as an entry of a batch, sent by Client.Batch.", o.Name, o.Name))
		fmt.Fprintf(&b, "func (BatchCalls) %s(%s) *Call[%s] {\n", o.Name, strings.Join(declared, ", "), o.Answer)
		if prelude == "" {
			prelude = ""
		}
		fmt.Fprintf(&b, "%s\treturn newCall(&op%s, %s, %s, %s, %s)\n}\n\n", prelude, o.Name, pathValues, query, body, o.decoder())
	}
	excluded := []string{}
	for _, id := range notInABatch {
		excluded = append(excluded, goName(id))
	}
	fmt.Fprintf(&b, "// notInABatch are the operations a batch cannot carry.\nvar notInABatch = %#v\n", excluded)
	return b.String()
}

// emitTypes writes the spec's own components: Scheduling's records and answers, and the problem
// the other services answer an error with.
func emitTypes(s *spec) (string, error) {
	var b strings.Builder
	b.WriteString(generatedHeader + "package haau3\n\n")
	var emit func(name, desc string, schema object, at pointer) error
	emit = func(name, desc string, schema object, at pointer) error {
		props, _ := schema["properties"].(object)
		required := map[string]bool{}
		for _, r := range asList(schema["required"]) {
			required[r.(string)] = true
		}
		var nested []func() error
		if desc != "" {
			comment(&b, "", fmt.Sprintf("%s: %s", name, desc))
		}
		fmt.Fprintf(&b, "type %s struct {\n", name)
		for _, key := range s.order.keys(at.to("properties"), props) {
			prop := props[key].(object)
			goType, err := s.dtoType(name, key, prop, at.to("properties", key), &nested, emit)
			if err != nil {
				return err
			}
			doc := ""
			if d, ok := prop["description"].(string); ok {
				doc = firstSentence(d)
			}
			if enum := asList(prop["enum"]); enum != nil {
				var values []string
				for _, v := range enum {
					values = append(values, fmt.Sprint(v))
				}
				doc = strings.TrimSpace(doc + " One of: " + strings.Join(values, ", ") + ".")
			}
			if doc != "" {
				comment(&b, "\t", doc)
			}
			tag := key
			if !required[key] {
				tag += ",omitempty"
				if !strings.HasPrefix(goType, "[]") && goType != "any" {
					goType = "*" + goType
				}
			}
			fmt.Fprintf(&b, "\t%s %s `json:\"%s\"`\n", goName(key), goType, tag)
		}
		b.WriteString("}\n\n")
		for _, n := range nested {
			if err := n(); err != nil {
				return err
			}
		}
		return nil
	}
	for _, name := range s.ownTypes {
		desc, _ := s.schemas[name]["description"].(string)
		if err := emit(name, firstSentence(desc), s.schemas[name], pointer{"components", "schemas", name}); err != nil {
			return "", err
		}
	}
	if out := b.String(); strings.Contains(out, "time.Time") {
		return strings.Replace(out, "package haau3\n\n", "package haau3\n\nimport \"time\"\n\n", 1), nil
	}
	return b.String(), nil
}

func (s *spec) dtoType(owner, key string, prop object, at pointer, nested *[]func() error,
	emit func(string, string, object, pointer) error) (string, error) {
	if ref, ok := prop["$ref"].(string); ok {
		return refName(ref), nil
	}
	if kinds := asList(prop["type"]); kinds != nil {
		return "any", nil // a value of more than one JSON type: ProblemIssue's path, of names and indexes
	}
	switch prop["type"] {
	case "string":
		if prop["format"] == "date-time" {
			return "time.Time", nil // RFC 3339, as encoding/json reads and writes a time.Time
		}
		return "string", nil
	case "integer":
		return "int", nil
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	case "array":
		items := prop["items"].(object)
		if items["type"] == "object" {
			t := owner + goName(singular(key))
			*nested = append(*nested, func() error { return emit(t, "", items, at.to("items")) })
			return "[]" + t, nil
		}
		t, err := s.dtoType(owner, singular(key), items, at.to("items"), nested, emit)
		return "[]" + t, err
	case "object":
		t := owner + goName(key)
		*nested = append(*nested, func() error { return emit(t, "", prop, at) })
		return t, nil
	}
	return "", fmt.Errorf("%s.%s has a schema the generator does not read", owner, key)
}

// literal is a spec example as a Go value of the given query kind.
func literal(kind string, required bool, example any) string {
	value := func(v any) string {
		switch kind {
		case "time":
			return fmt.Sprintf("exampleTime(%q)", fmt.Sprint(v))
		case "int":
			f, _ := v.(float64)
			return strconv.Itoa(int(f))
		case "bool":
			return strconv.FormatBool(fmt.Sprint(v) == "true")
		}
		return strconv.Quote(fmt.Sprint(v))
	}
	if kind == "strings" {
		items := []string{}
		if list, ok := example.([]any); ok {
			for _, v := range list {
				items = append(items, value(v))
			}
		} else {
			items = append(items, value(example))
		}
		return "[]string{" + strings.Join(items, ", ") + "}"
	}
	if required {
		return value(example)
	}
	return "new(" + value(example) + ")"
}

// wireTime is a time example as Go writes a time.Time into a query: RFC 3339 with its offset.
func wireTime(example any) string {
	t, err := time.Parse(time.RFC3339Nano, fmt.Sprint(example))
	if err != nil {
		panic(fmt.Sprintf("the spec's time example %v is not RFC 3339", example))
	}
	return t.Format(time.RFC3339Nano)
}

// wire is a spec example as the query sends it, one value per pair.
func wire(example any) []string {
	list, ok := example.([]any)
	if !ok {
		list = []any{example}
	}
	var out []string
	for _, v := range list {
		switch v := v.(type) {
		case float64:
			out = append(out, strconv.FormatFloat(v, 'f', -1, 64))
		default:
			out = append(out, fmt.Sprint(v))
		}
	}
	return out
}

// emitExamplesTest writes a test table: each operation called with its spec example, typed, so the
// compiler checks every example as a customer would write it.
func emitExamplesTest(s *spec) string {
	var b strings.Builder
	b.WriteString(generatedHeader + "package haau3\n\nimport (\n\t\"context\"\n\n\t\"github.com/haau3/haau3-go/fhir\"\n)\n\n")
	b.WriteString("var _ = fhir.DecodeResource\n\n")
	b.WriteString("// specExamples is every operation of the spec, called with the spec's own example.\nvar specExamples = []specExample{\n")
	for _, o := range s.Operations {
		fmt.Fprintf(&b, "\t{\n\t\tid: %q, name: %q, method: %q, path: %q,\n", o.ID, o.Name, o.Method, o.Path)
		if len(o.PathExample) > 0 {
			fmt.Fprintf(&b, "\t\tpathValues: %#v,\n", o.PathExample)
		}
		var sent []string
		var fields []string
		for _, p := range o.Query {
			if p.Example == nil {
				continue
			}
			values := wire(p.Example)
			if p.Kind == "time" {
				values = []string{wireTime(p.Example)}
			}
			for _, v := range values {
				sent = append(sent, fmt.Sprintf("{%q, %q}", p.Wire, v))
			}
			fields = append(fields, fmt.Sprintf("%s: %s", p.Name, literal(p.Kind, p.Required, p.Example)))
		}
		if len(sent) > 0 {
			fmt.Fprintf(&b, "\t\tsent: []pair{%s},\n", strings.Join(sent, ", "))
		}
		if o.BodyExample != nil {
			fmt.Fprintf(&b, "\t\tbody: %s,\n", goRawString(o.BodyExample))
		}
		fmt.Fprintf(&b, "\t\tanswer: %s,\n", goRawString(o.Example))
		var args []string
		for _, v := range o.PathExample {
			args = append(args, strconv.Quote(v))
		}
		bodySetup := ""
		if o.Body != "" {
			if o.Body == "fhir.Resource" {
				bodySetup = "\t\t\tbody := exampleResource(ex.body)\n"
			} else {
				bodySetup = fmt.Sprintf("\t\t\tbody := exampleBody[%s](ex.body)\n", strings.TrimPrefix(o.Body, "*"))
			}
			args = append(args, "body")
		}
		if len(o.Query) > 0 {
			args = append(args, fmt.Sprintf("%s{%s}", o.ParamsType(), strings.Join(fields, ", ")))
		}
		fmt.Fprintf(&b, "\t\tcall: func(ctx context.Context, c *Client, ex specExample, opts ...Option) (any, error) {\n%s\t\t\treturn c.%s(%s)\n\t\t},\n",
			bodySetup, o.Name, strings.Join(append([]string{"ctx"}, append(args, "opts...")...), ", "))
		if o.Batchable {
			fmt.Fprintf(&b, "\t\tentry: func(ex specExample) entryProbe {\n%s\t\t\treturn probe(Calls.%s(%s))\n\t\t},\n",
				bodySetup, o.Name, strings.Join(args, ", "))
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return b.String()
}

func goRawString(raw json.RawMessage) string {
	if !strings.Contains(string(raw), "`") {
		return "`" + string(raw) + "`"
	}
	return strconv.Quote(string(raw))
}

// apiMD writes api.md: every method by service, each linking its page on docs.haau3.com.
func apiMD(s *spec) string {
	tagOrder := map[string]int{}
	for i, t := range s.Tags {
		tagOrder[t.Name] = i
	}
	byTag := map[string][]operation{}
	ops := slices.Clone(s.Operations)
	slices.SortStableFunc(ops, func(a, b operation) int {
		return strings.Compare(a.Path+" "+a.Method, b.Path+" "+b.Method)
	})
	var tags []string
	for _, o := range ops {
		if _, ok := byTag[o.Tag]; !ok {
			tags = append(tags, o.Tag)
		}
		byTag[o.Tag] = append(byTag[o.Tag], o)
	}
	slices.SortStableFunc(tags, func(a, b string) int {
		ia, oka := tagOrder[a]
		ib, okb := tagOrder[b]
		if !oka {
			ia = 99
		}
		if !okb {
			ib = 99
		}
		return ia - ib
	})
	desc := map[string]string{}
	for _, t := range s.Tags {
		desc[t.Name] = t.Description
	}
	batchable := 0
	for _, o := range s.Operations {
		if o.Batchable {
			batchable++
		}
	}
	var excluded []string
	for _, id := range notInABatch {
		excluded = append(excluded, "`"+goName(id)+"`")
	}
	var b strings.Builder
	b.WriteString("<!-- Generated by internal/cmd/generate from openapi/openapi.json. Do not edit by hand. -->\n\n# API reference\n\n")
	fmt.Fprintf(&b, "Every operation of the haau3 platform API (`%s`) is a method on `*haau3.Client`, named by\n", s.Version)
	b.WriteString(`its operationId in Go's style (` + "`fhirMetadata` is `FHIRMetadata`" + `). Each links to its page on
docs.haau3.com, which shows its parameters and an example exchange. Every method takes a
` + "`context.Context`" + ` first; then the path values; then ` + "`body`" + ` for an operation that takes one;
then its query parameters as a struct, ` + "`<Method>Params`" + `, whose fields are the API's own names in
Go's style (` + "`name:contains` is `NameContains`, `_count` is `Count`" + `), each documented with both.
Every method also takes the per-call options ` + "`WithTimeout`, `WithMaxRetries`, `WithCorrelationID`,\n`WithHeader`, `WithAPIKey` and `WithResponseInfo`" + `, which gives the request id and timing too.
`)
	fmt.Fprintf(&b, "\n`Client.Batch` sends several of these as one request, each with its own answer or error, from the\nentries `haau3.Calls` makes. It takes every operation on the FHIR base except %s:\n%d of the %d. See the README's \"Several requests in one\".\n", strings.Join(excluded, " and "), batchable, len(s.Operations))
	for _, tag := range tags {
		fmt.Fprintf(&b, "\n## %s\n\n%s\n\n| Method | Request | What it does |\n|---|---|---|\n", tag, desc[tag])
		for _, o := range byTag[tag] {
			_, names := o.methodArgs()
			sig := fmt.Sprintf("%s(%s)", o.Name, strings.Join(append([]string{"ctx"}, names...), ", "))
			fmt.Fprintf(&b, "| [`%s`](%s) | `%s %s` | %s |\n", sig, o.Docs, o.Method, o.Path, o.Summary)
		}
	}
	return b.String()
}
